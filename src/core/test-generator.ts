export const BASE_URL = (process.env.NATIV_TEST_BASE_URL || __NATIV_BASE_URL__).replace(/\/+$/, '');

/** A parsed contract descriptor (see src/core/test-generator-types.ts in nativ). */
export type SchemaNode = Record<string, any>;

export interface ContractRequest {
  method: string;
  path: string;
  query?: Record<string, string>;
  headers?: Record<string, string>;
  body?: unknown;
}

export interface ContractResponse {
  status: number;
  body: unknown;
}

export async function callEndpoint(request: ContractRequest, options: { anonymous?: boolean } = {}): Promise<ContractResponse> {
  const url = new URL(BASE_URL + request.path);
  for (const [key, value] of Object.entries(request.query ?? {})) url.searchParams.set(key, value);
  const headers: Record<string, string> = { Accept: 'application/json', ...(request.headers ?? {}) };
  const auth = process.env.NATIV_TEST_AUTH_HEADER;
  if (auth && !options.anonymous) headers.Authorization = auth;
  const init: RequestInit = { method: request.method, headers };
  if (request.body !== undefined) {
    headers['Content-Type'] = 'application/json';
    init.body = JSON.stringify(request.body);
  }
  const res = await fetch(url, init);
  const text = await res.text();
  let body: unknown = text;
  try {
    body = text ? JSON.parse(text) : null;
  } catch {
    // Non-JSON bodies are returned as text.
  }
  return { status: res.status, body };
}

function describeValue(value: unknown): string {
  if (value === null) return 'null';
  return Array.isArray(value) ? 'array' : typeof value;
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function primitiveMatches(value: unknown, type: string): boolean {
  switch (type) {
    case 'string': return typeof value === 'string';
    case 'number': return typeof value === 'number' && Number.isFinite(value);
    case 'integer': return Number.isInteger(value);
    case 'boolean': return typeof value === 'boolean';
    case 'null': return value === null;
    default: return true;
  }
}

/** Every way value deviates from the contract schema; empty when it conforms. */
export function shapeErrors(value: unknown, node: SchemaNode, path = '$'): string[] {
  switch (node.kind) {
    case 'primitive':
      return primitiveMatches(value, node.type) ? [] : [path + ': expected ' + node.type + ', got ' + describeValue(value)];
    case 'enum':
      return node.values.includes(value) ? [] : [path + ': expected one of ' + JSON.stringify(node.values) + ', got ' + JSON.stringify(value)];
    case 'ref':
      return isPlainObject(value) ? [] : [path + ': expected ' + node.name + ' object, got ' + describeValue(value)];
    case 'array':
      if (!Array.isArray(value)) return [path + ': expected array, got ' + describeValue(value)];
      return value.flatMap((item, i) => shapeErrors(item, node.items, path + '[' + i + ']'));
    case 'union':
      return node.variants.some((v: SchemaNode) => shapeErrors(value, v, path).length === 0)
        ? []
        : [path + ': ' + JSON.stringify(value) + ' matches none of the allowed types'];
    case 'object': {
      if (!isPlainObject(value)) return [path + ': expected object, got ' + describeValue(value)];
      const errors: string[] = [];
      for (const [key, child] of Object.entries(node.properties as Record<string, SchemaNode>)) {
        if (value[key] === undefined) {
          if (!child.optional) errors.push(path + '.' + key + ': missing required field');
          continue;
        }
        errors.push(...shapeErrors(value[key], child, path + '.' + key));
      }
      return errors;
    }
    default:
      return [];
  }
}

// ─── Live database schema (structure only, read through nativ; never rows or credentials) ───

export interface LiveColumn {
  name: string;
  primaryKey?: boolean;
  nullable?: boolean;
}

export interface LiveIndex {
  name: string;
  columns: string[];
  unique: boolean;
}

export interface LiveTable {
  name: string;
  columns: LiveColumn[];
  indexes?: LiveIndex[];
}

export interface LiveSchema {
  connected: boolean;
  error: string | null;
  tables: LiveTable[];
}

/** A generated database assertion: { kind, table, column?, columns?, nullable? }. */
export type DbAssertion = Record<string, any>;

let liveSchemaCache: LiveSchema | undefined;

function readInspectOutput(): string {
  const file = process.env.NATIV_DB_SCHEMA_JSON;
  if (file) return readFileSync(file, 'utf8');
  const command = process.env.NATIV_DB_INSPECT_CMD || 'nativ db inspect --json';
  try {
    return execSync(command, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 120000 });
  } catch (err: any) {
    // nativ exits 1 when the database is unreachable but still prints the JSON status.
    return String(err?.stdout ?? '');
  }
}

export function loadLiveSchema(): LiveSchema {
  if (liveSchemaCache) return liveSchemaCache;
  let parsed: any = null;
  try {
    const raw = readInspectOutput();
    parsed = JSON.parse(raw.slice(raw.indexOf('{'), raw.lastIndexOf('}') + 1));
  } catch {
    parsed = null;
  }
  liveSchemaCache = parsed
    ? { connected: parsed.status?.connected === true, error: parsed.status?.error ?? null, tables: Array.isArray(parsed.tables) ? parsed.tables : [] }
    : { connected: false, error: 'could not read "nativ db inspect --json" output (set NATIV_DB_SCHEMA_JSON or NATIV_DB_INSPECT_CMD)', tables: [] };
  return liveSchemaCache;
}

