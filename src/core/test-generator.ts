/**
 * Contract-to-test generator (nativ test gen).
 *
 * Contracts are compiled into framework-agnostic TestSuiteSpecs, then rendered by a
 * TestFrameworkAdapter. Generated endpoint tests never send a well-formed request to a
 * mutating endpoint: POST/PUT/PATCH/DELETE are only exercised with invalid or anonymous
 * requests, so running the suite cannot write data or trigger side effects.
 */

/** Present in the header of every generated file; files without it are never overwritten. */
export const GENERATED_MARKER = 'Code generated by nativ test gen';
const GENERATED_MARKER_PATTERN = /code generated by nativ test gen/i;

export class TestGenError extends Error {
  constructor(
    public readonly code: string,
    message: string,
  ) {
    super(message);
    this.name = 'TestGenError';
  }
}

// ─── Options & contract loading ────────────────────────────────────────────

export function resolveTestGenOptions(options: TestGenOptions): ResolvedTestGenOptions {
  const targetDir = path.resolve(options.targetDir);

  const framework = options.framework ?? DEFAULT_TEST_FRAMEWORK;
  if (!isTestFramework(framework)) {
    throw new TestGenError('INVALID_FRAMEWORK', `Unsupported framework "${framework}". Expected one of: ${TEST_FRAMEWORKS.join(', ')}`);
  }

  const baseUrl = (options.baseUrl ?? DEFAULT_TEST_BASE_URL).trim().replace(/\/+$/, '');
  let parsed: URL | null = null;
  try {
    parsed = new URL(baseUrl);
  } catch {
    parsed = null;
  }
  if (!parsed || (parsed.protocol !== 'http:' && parsed.protocol !== 'https:')) {
    throw new TestGenError('INVALID_BASE_URL', `Base URL must be an absolute http(s) URL, got "${baseUrl}"`);
  }

  const outputDir = path.resolve(targetDir, options.outputDir || DEFAULT_TEST_OUTPUT_DIR);
  return { targetDir, outputDir, framework, baseUrl, dryRun: options.dryRun === true };
}

function readContractJson<T>(targetDir: string, file: string): T | null {
  const filePath = path.join(targetDir, '.ai', file);
  if (!fs.existsSync(filePath)) return null;
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8')) as T;
  } catch (err) {
    throw new TestGenError('INVALID_CONTRACT', `.ai/${file} is not valid JSON: ${err instanceof Error ? err.message : String(err)}`);
  }
}

export function loadApiContracts(targetDir: string): ApiContractsDocument | null {
  const doc = readContractJson<ApiContractsDocument>(targetDir, 'api_contracts.json');
  if (!doc) return null;
  if (!Array.isArray(doc.endpoints)) {
    throw new TestGenError('INVALID_CONTRACT', '.ai/api_contracts.json must contain an "endpoints" array');
  }
  return doc;
}

/** .ai/db_schema.json with tables normalized the same way `nativ db diff --target contract` reads them. */
export function loadDbSchemaContract(targetDir: string): DbSchemaDocument | null {
  const doc = readContractJson<Partial<DbSchemaDocument>>(targetDir, 'db_schema.json');
  if (!doc) return null;
  if (doc.tables !== undefined && !Array.isArray(doc.tables)) {
    throw new TestGenError('INVALID_CONTRACT', '.ai/db_schema.json "tables" must be an array');
  }
  const engine = loadContractEngine(targetDir);
  return {
    version: doc.version,
    projectName: doc.projectName ?? '',
    ...(engine ? { engine } : {}),
    tables: loadContractTables(targetDir),
  } as DbSchemaDocument;
}

// ─── Schema helpers ────────────────────────────────────────────────────────

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** Same semantics as the generated shapeErrors helpers: true when `value` conforms to `node`. */
export function matchesSchema(value: unknown, node: SchemaNode): boolean {
  switch (node.kind) {
    case 'primitive':
      switch (node.type) {
        case 'string':
          return typeof value === 'string';
        case 'number':
          return typeof value === 'number' && Number.isFinite(value);
        case 'integer':
          return Number.isInteger(value);
        case 'boolean':
          return typeof value === 'boolean';
        case 'null':
          return value === null;
        default:
          return true;
      }
    case 'enum':
      return node.values.includes(value as string | number);
    case 'ref':
      return isPlainObject(value);
    case 'array':
      return Array.isArray(value) && value.every((item) => matchesSchema(item, node.items));
    case 'union':
      return node.variants.some((v) => matchesSchema(value, v));
    case 'object':
      if (!isPlainObject(value)) return false;
      return Object.entries(node.properties).every(([key, child]) =>
        value[key] === undefined ? child.optional === true : matchesSchema(value[key], child),
      );
  }
}

/** A plausible valid value for `node` (enums use their first value). */
function sampleValue(node: SchemaNode): unknown {
  switch (node.kind) {
    case 'enum':
      return node.values[0];
    case 'primitive':
      if (node.type === 'number' || node.type === 'integer') return 1;
      if (node.type === 'boolean') return true;
      if (node.type === 'null') return null;
      return 'sample';
    case 'object':
      return Object.fromEntries(
        Object.entries(node.properties)
          .filter(([, child]) => !child.optional)
          .map(([key, child]) => [key, sampleValue(child)]),
      );
    case 'array':
      return [];
    case 'union': {
      const nonNull = node.variants.find((v) => !(v.kind === 'primitive' && v.type === 'null'));
      return sampleValue(nonNull ?? node.variants[0]);
    }
    case 'ref':
      return {};
  }
}

const INVALID_CANDIDATES: unknown[] = [12345, '__nativ_invalid__', true, ['__nativ_invalid__']];

/** A value `node` rejects, or undefined when it accepts anything. */
function invalidValue(node: SchemaNode): unknown {
  return INVALID_CANDIDATES.find((candidate) => !matchesSchema(candidate, node));
}

function toObjectNode(value: ContractFieldValue | undefined): ObjectNode | null {
  if (value === null || value === undefined) return null;
  const node = buildSchemaNode(value);
  return node.kind === 'object' && !node.open ? node : null;
}

function requiredEntries(node: ObjectNode | null): Array<[string, SchemaNode]> {
  return node ? Object.entries(node.properties).filter(([, child]) => !child.optional) : [];
}

function stringifyQuery(values: Record<string, unknown>): Record<string, string> {
  return Object.fromEntries(Object.entries(values).map(([k, v]) => [k, String(v)]));
}

function quoteList(names: string[]): string {
  return names.map((n) => `"${n}"`).join(', ');
}

// ─── Endpoint suite synthesis ──────────────────────────────────────────────

const HTTP_METHODS: readonly HttpMethod[] = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE'];
const SAFE_METHODS = new Set<HttpMethod>(['GET']);
const INVALID_INPUT_STATUSES = [400, 422];
const PATH_PARAM_PATTERN = /:([A-Za-z_]\w*)|\{([A-Za-z_]\w*)\}/g;

interface InvalidRequest {
  request: TestRequestSpec;
  reason: string;
}

/** Builds a request the contract says must be rejected, or null when no input can be invalidated. */
function buildInvalidRequest(
  base: TestRequestSpec,
  queryNode: ObjectNode | null,
  bodyNode: SchemaNode | null,
  safe: boolean,
): InvalidRequest | null {
  const requiredQuery = requiredEntries(queryNode);
  const sampleQuery = stringifyQuery(Object.fromEntries(requiredQuery.map(([k, n]) => [k, sampleValue(n)])));
  const withQuery = Object.keys(sampleQuery).length ? { query: sampleQuery } : {};

  if (!safe && bodyNode) {
    if (bodyNode.kind === 'object' && !bodyNode.open) {
      const required = requiredEntries(bodyNode).map(([k]) => k);
      if (required.length) {
        return {
          request: { ...base, ...withQuery, body: {} },
          reason: `missing required field${required.length > 1 ? 's' : ''} ${quoteList(required)}`,
        };
      }
      for (const [key, child] of Object.entries(bodyNode.properties)) {
        const bad = invalidValue(child);
        if (bad !== undefined) return { request: { ...base, ...withQuery, body: { [key]: bad } }, reason: `"${key}" has the wrong type` };
      }
    } else {
      const bad = invalidValue(bodyNode);
      if (bad !== undefined) return { request: { ...base, ...withQuery, body: bad }, reason: 'body has the wrong type' };
    }
  }

  if (requiredQuery.length) {
    const names = requiredQuery.map(([k]) => k);
    return { request: { ...base }, reason: `missing required query parameter${names.length > 1 ? 's' : ''} ${quoteList(names)}` };
  }

  const enumParam = queryNode && Object.entries(queryNode.properties).find(([, n]) => n.kind === 'enum' && n.base === 'string');
  if (enumParam) {
    return { request: { ...base, query: { [enumParam[0]]: '__nativ_invalid__' } }, reason: `"${enumParam[0]}" is outside its allowed values` };
  }
  return null;
}

function successStatus(endpoint: ApiEndpointContract): number | null {
  const codes = Object.keys(endpoint.responses ?? {})
    .map(Number)
    .filter((c) => c >= 200 && c < 300)
    .sort((a, b) => a - b);
  return codes[0] ?? null;
}

export function buildEndpointSuite(endpoint: ApiEndpointContract): TestSuiteSpec {
  const method = String(endpoint.method ?? '').toUpperCase() as HttpMethod;
  if (!HTTP_METHODS.includes(method) || typeof endpoint.path !== 'string' || !endpoint.path.startsWith('/')) {
    throw new TestGenError('INVALID_CONTRACT', `Endpoint "${endpoint.id}" needs an HTTP method and a path starting with "/"`);
  }
  const id = endpoint.id || `${method} ${endpoint.path}`;
  const request = endpoint.request ?? {};

  const pathNode = toObjectNode(request.pathParams);
  let hasPathParams = false;
  const filledPath = endpoint.path.replace(PATH_PARAM_PATTERN, (_m, colon: string | undefined, brace: string | undefined) => {
    hasPathParams = true;
    const name = colon ?? brace ?? '';
    const node = pathNode?.properties[name];
    return encodeURIComponent(String(node ? sampleValue(node) : 'sample'));
  });

  // Authorization comes from NATIV_TEST_AUTH_HEADER at run time; Content-Type is set when a body is sent.
  const headers = Object.fromEntries(
    Object.entries(request.headers ?? {}).filter(([k, v]) => typeof v === 'string' && !/^(authorization|content-type)$/i.test(k)),
  );
  const base: TestRequestSpec = { method, path: filledPath, ...(Object.keys(headers).length ? { headers } : {}) };

  const queryNode = toObjectNode(request.queryParams);
  const bodyNode = request.body === null || request.body === undefined ? null : buildSchemaNode(request.body);
  const safe = SAFE_METHODS.has(method);
  const needsInputs = requiredEntries(queryNode).length > 0 || hasPathParams;
  const invalid = buildInvalidRequest(base, queryNode, bodyNode, safe);

  // Well-formed requests are only sent to safe endpoints that need no caller-supplied values.
  const sampleRequest = safe && !needsInputs ? base : null;
  const probeRequest = sampleRequest ?? invalid?.request ?? null;
  const cases: TestCaseSpec[] = [];

  if (probeRequest && !hasPathParams) {
    cases.push({ id: `${id}:route`, name: 'route is mounted (not 404/405)', kind: 'route', request: probeRequest, assertions: [] });
  }

  if (endpoint.auth) {
    // Without an invalid request, a mutating endpoint is probed bare: it must reject before acting.
    cases.push({
      id: `${id}:auth-required`,
      name: 'rejects anonymous requests with 401',
      kind: 'auth-required',
      request: probeRequest ?? base,
      assertions: [{ kind: 'status', expected: 401 }],
    });
  }

  if (invalid) {
    cases.push({
      id: `${id}:invalid-payload`,
      name: `rejects invalid input with 400/422 (${invalid.reason})`,
      kind: 'invalid-payload',
      request: invalid.request,
      assertions: [{ kind: 'status', expected: INVALID_INPUT_STATUSES }],
    });
  }

  const status = successStatus(endpoint);
  if (sampleRequest && status !== null) {
    const assertions: TestAssertion[] = [{ kind: 'status', expected: status }];
    const body = endpoint.responses[String(status)]?.body;
    if (body !== undefined) assertions.push({ kind: 'response-shape', schema: buildSchemaNode(body) });
    cases.push({
      id: `${id}:response-schema`,
      name: `returns ${status} matching the contract response schema`,
      kind: 'response-schema',
      request: sampleRequest,
      assertions,
    });
  }

  return {
    id,
    name: `${method} ${endpoint.path}`,
    suiteType: 'api-contract',
    source: { kind: 'endpoint', endpointId: id, method, path: endpoint.path },
    cases,
  };
}

export function buildEndpointSuites(doc: ApiContractsDocument): TestSuiteSpec[] {
  return doc.endpoints.map(buildEndpointSuite).filter((suite) => suite.cases.length > 0);
}

// ─── Database integrity suite synthesis ────────────────────────────────────

/** Engines without unique secondary indexes; unique-constraint checks would always fail there. */
const NO_UNIQUE_INDEX_ENGINES = new Set<DatabaseEngine>(['firestore']);

/**
 * Integrity checks for one contract table: existence, columns, primary key, nullability and
 * unique constraints. Collections only get required-field checks, because sampled document
 * stores report a field as nullable whenever some sampled document lacks it.
 */
export function buildTableSuite(table: TableSchema, engine: DatabaseEngine | null): TestSuiteSpec {
  const t = table.name;
  const entityType = table.entityType ?? (engine && isNoSqlEngine(engine) ? 'collection' : 'table');
  const isCollection = entityType === 'collection';
  const fieldWord = isCollection ? 'field' : 'column';
  const cases: TestCaseSpec[] = [
    { id: `db:${t}:exists`, name: `${entityType} exists`, kind: 'table-exists', assertions: [{ kind: 'table-exists', table: t }] },
  ];

  for (const col of table.columns) {
    cases.push({
      id: `db:${t}:column:${col.name}`,
      name: `has ${fieldWord} "${col.name}" (${col.type})`,
      kind: 'column',
      assertions: [{ kind: 'column-exists', table: t, column: col.name, type: col.type }],
    });
  }

  const pkColumns = table.columns.filter((c) => c.primaryKey).map((c) => c.name);
  if (pkColumns.length) {
    cases.push({
      id: `db:${t}:primary-key`,
      name: `primary key is (${pkColumns.join(', ')})`,
      kind: 'primary-key',
      assertions: [{ kind: 'primary-key', table: t, columns: pkColumns }],
    });
  }

  for (const col of table.columns) {
    if (col.primaryKey || col.isSubcollection || (isCollection && col.nullable)) continue;
    cases.push({
      id: `db:${t}:nullability:${col.name}`,
      name: col.nullable ? `"${col.name}" is nullable` : isCollection ? `"${col.name}" is always present` : `"${col.name}" is NOT NULL`,
      kind: 'nullability',
      assertions: [{ kind: 'nullability', table: t, column: col.name, nullable: col.nullable }],
    });
  }

  if (!engine || !NO_UNIQUE_INDEX_ENGINES.has(engine)) {
    for (const idx of table.indexes ?? []) {
      if (!idx.unique || !idx.columns.length) continue;
      cases.push({
        id: `db:${t}:unique:${idx.name}`,
        name: `unique constraint ${idx.name} on (${idx.columns.join(', ')})`,
        kind: 'unique-constraint',
        assertions: [{ kind: 'unique-constraint', table: t, index: idx.name, columns: idx.columns }],
      });
    }
  }

  return {
    id: `db:${t}`,
    name: `${entityType} ${t}`,
    suiteType: 'db-integrity',
    source: { kind: 'table', table: t, entityType },
    cases,
  };
}

export function buildDbSuites(doc: DbSchemaDocument): TestSuiteSpec[] {
  return doc.tables.map((table) => buildTableSuite(table, doc.engine ?? null));
}

// ─── Rendering helpers ─────────────────────────────────────────────────────

function slug(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'suite';
}

function snake(value: string): string {
  const s = value.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'suite';
  return /^\d/.test(s) ? `_${s}` : s;
}

function pascal(value: string): string {
  const s = value
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
  return /^\d/.test(s) ? `X${s}` : s || 'Suite';
}

/** Indents every line after the first, so multi-line literals nest under the current line. */
function hang(text: string, pad: string): string {
  return text.split('\n').join(`\n${pad}`);
}

function statusList(expected: number | number[]): number[] {
  return Array.isArray(expected) ? expected : [expected];
}

function suiteHeader(comment: string, suite: TestSuiteSpec): string[] {
  const source =
    suite.source.kind === 'endpoint'
      ? `.ai/api_contracts.json (endpoint "${suite.source.endpointId}")`
      : `.ai/db_schema.json (${suite.source.entityType} "${suite.source.table}")`;
  return [`${comment} ${GENERATED_MARKER} from ${source}. DO NOT EDIT.`, `${comment} Re-run \`nativ test gen\` to refresh this file.`];
}

function pyLiteral(value: unknown, depth = 0): string {
  if (value === null || value === undefined) return 'None';
  if (value === true) return 'True';
  if (value === false) return 'False';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'None';
  if (typeof value === 'string') return JSON.stringify(value);
  const pad = '    '.repeat(depth + 1);
  const close = '    '.repeat(depth);
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    return `[\n${value.map((v) => pad + pyLiteral(v, depth + 1)).join(',\n')},\n${close}]`;
  }
  const entries = Object.entries(value as Record<string, unknown>).filter(([, v]) => v !== undefined);
  if (!entries.length) return '{}';
  return `{\n${entries.map(([k, v]) => `${pad}${JSON.stringify(k)}: ${pyLiteral(v, depth + 1)}`).join(',\n')},\n${close}}`;
}

function pyTuple(values: number[]): string {
  return values.length === 1 ? `(${values[0]},)` : `(${values.join(', ')})`;
}

/** A JSON document as a Go (and JSON) double-quoted string literal. */
function goJson(value: unknown): string {
  return JSON.stringify(JSON.stringify(value));
}

function applyBaseUrl(source: string, baseUrl: string): string {
  return source.replace('__NATIV_BASE_URL__', JSON.stringify(baseUrl));
}

