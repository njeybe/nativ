function toDisplayPath(targetDir: string, filePath: string): string {
  const rel = path.relative(targetDir, filePath);
  const inside = rel === '' || (!rel.startsWith('..') && !path.isAbsolute(rel));
  return (inside ? rel || '.' : filePath).split(path.sep).join('/');
}

/** Writes generated files, refusing to overwrite any file that was not generated by nativ. */
function writeGeneratedFiles(outputDir: string, files: GeneratedTestFile[]): void {
  const resolved = files.map((file) => {
    const filePath = path.resolve(outputDir, file.relativePath);
    const rel = path.relative(outputDir, filePath);
    if (rel.startsWith('..') || path.isAbsolute(rel)) {
      throw new TestGenError('INVALID_OUTPUT_PATH', `Generated path escapes the output directory: ${file.relativePath}`);
    }
    return { filePath, file };
  });

  for (const { filePath, file } of resolved) {
    if (!fs.existsSync(filePath)) continue;
    const head = fs.readFileSync(filePath, 'utf8').slice(0, 512);
    if (!GENERATED_MARKER_PATTERN.test(head)) {
      throw new TestGenError('OUTPUT_CONFLICT', `Refusing to overwrite ${file.relativePath}: it was not generated by nativ test gen`);
    }
  }

  for (const { filePath, file } of resolved) {
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, file.content, 'utf8');
  }
}

/** Compiles .ai contracts into test files for the chosen framework (written unless dryRun). */
export function generateContractTests(options: TestGenOptions): TestGenResult {
  const started = Date.now();
  const opts = resolveTestGenOptions(options);
  const api = loadApiContracts(opts.targetDir);
  const db = loadDbSchemaContract(opts.targetDir);
  if (!api && !db) {
    throw new TestGenError('NO_CONTRACTS', `No .ai/api_contracts.json or .ai/db_schema.json found in ${opts.targetDir}`);
  }

  const endpointSuites = api ? buildEndpointSuites(api) : [];
  const tableSuites = db ? buildDbSuites(db) : [];
  const suites = [...endpointSuites, ...tableSuites];
  const adapter = TEST_FRAMEWORK_ADAPTERS[opts.framework];
  const ctx: TestRenderContext = {
    projectName: api?.projectName || db?.projectName || path.basename(opts.targetDir),
    baseUrl: opts.baseUrl,
    engine: db?.engine ?? null,
  };

  const files: GeneratedTestFile[] = suites.length ? [...(adapter.renderSupportFiles?.(ctx) ?? [])] : [];
  for (const suite of suites) {
    files.push({ relativePath: adapter.suiteFileName(suite), content: adapter.renderSuite(suite, ctx), suiteType: suite.suiteType });
  }

  if (!opts.dryRun) writeGeneratedFiles(opts.outputDir, files);

  return {
    projectName: ctx.projectName,
    framework: opts.framework,
    outputDir: toDisplayPath(opts.targetDir, opts.outputDir),
    files,
    endpointsCovered: endpointSuites.length,
    tablesCovered: tableSuites.length,
    durationMs: Date.now() - started,
  };
}
